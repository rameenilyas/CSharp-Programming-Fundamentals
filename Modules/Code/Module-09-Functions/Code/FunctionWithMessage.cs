### 02-FunctionWithMessage.cs

```csharp
using System;

class Program
{
    static void Main()
    {
        DisplayMessage();
    }

    static void DisplayMessage()
    {
        Console.WriteLine("Welcome to C# Programming!");
    }
}
```

### Explanation

**1. `Main()` Method**
The program starts execution from the `Main()` method.

**2. `DisplayMessage()` Function Call**
`DisplayMessage();` calls the function.

**3. `DisplayMessage()` Function**
This is a user-defined function that displays a message on the screen.

**4. `Console.WriteLine()`**
It prints the specified message on the console.

### Output

```text
Welcome to C# Programming!
```

### Key Concept

A function can contain statements that perform a specific task. We can call the function whenever we want to perform that task.
