



```csharp
using System;

class WhileLoop
{
    static void Main()
    {
        int i = 1;

        while (i <= 5)
        {
            Console.WriteLine(i);
            i++;
        }
    }
}
```

### Output:

```text
1
2
3
4
5
```

### Simple Explanation:

* `int i = 1` → Counting starts from **1**
* `while (i <= 5)` → Continue while `i` is **5 or less**
* `Console.WriteLine(i)` → Print the current value of `i`
* `i++` → Increase `i` by **1**

