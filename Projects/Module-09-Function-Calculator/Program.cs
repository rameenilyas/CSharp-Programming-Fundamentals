# Module 09 - Function-Based Calculator

## Project Description

This project is a simple C# console calculator that uses functions to perform basic mathematical operations.

## Features

- Addition
- Subtraction
- Multiplication
- Division
- Menu-based system
- User input
- Functions with parameters
- Functions with return values
- Switch statement
- Exit option

## Learning Objectives

This project helps practice:

- Creating functions
- Calling functions
- Parameters
- Arguments
- Return values
- `switch`
- User input
- Basic calculations

## Example

```text
===== Function Calculator =====
1. Addition
2. Subtraction
3. Multiplication
4. Division
5. Exit

